// Package frost provides a FROST (Flexible Round-Optimized Schnorr Threshold)
// threshold signer implementation for Ed25519, using the bytemare/frost library
// which implements RFC 9591.
//
// This package is unaudited. FROST threshold signing protects against key
// compromise by ensuring no single party ever holds the complete signing key.
// However, it does NOT protect against:
//
//   - A malicious coordinator who can select which signers participate and
//     can abort or manipulate the signing ceremony.
//   - Side-channel attacks on individual participants' key shares.
//   - Compromise of the trusted dealer during key generation (if using
//     centralized keygen; distributed key generation is recommended).
//   - Denial of service if insufficient signers are available.
//   - Replay attacks on the commitment round (commitments must be fresh per
//     signing session).
//
// The aggregated signature verifies under the standard Ed25519 verifier,
// and is byte-compatible with signatures produced by NewEd25519Signer for
// a reconstructed key.
//
// For production use, consider using a distributed key generation (DKG)
// protocol such as the one in github.com/bytemare/dkg rather than the
// trusted dealer keygen used here for testing.
package frost

import (
	"context"
	"crypto/ed25519"
	"crypto/rand"
	"errors"
	"fmt"
	"sync"

	"github.com/bytemare/frost"
	"github.com/bytemare/frost/debug"
	"github.com/bytemare/secret-sharing/keys"

	"github.com/soroauth/soroauth-go"
	"github.com/stellar/go-stellar-sdk/strkey"
	"github.com/stellar/go-stellar-sdk/xdr"
)

// DefaultCiphersuite is the Ed25519 ciphersuite (Edwards25519 + SHA-512)
// producing Ed25519-compatible signatures per RFC 8032.
const DefaultCiphersuite = frost.Ed25519

// FROSTCoordinator orchestrates a FROST threshold signing ceremony. It holds
// the group configuration (verification key, public key shares, threshold)
// and aggregates signature shares from participants into the final signature.
//
// The coordinator does NOT hold any secret key material.
type FROSTCoordinator struct {
	cfg       *frost.Configuration
	threshold uint16
	address   string // G... account address the group signs for
	mu        sync.Mutex
	sessions  map[int64]*frostSigningSession
	roundGen  func() (int64, error)
}

// frostSigningSession holds the state of an active signing round.
type frostSigningSession struct {
	round       int64
	commitments frost.CommitmentList
	message     [32]byte
	sigShares   []*frost.SignatureShare
	complete    bool
	signature   []byte
}

// NewFROSTCoordinator creates a coordinator for a threshold signing group.
// The key shares must have been generated by a trusted dealer or DKG.
// The verificationKey is the group public key (32 bytes).
// The publicKeyShares are the public key shares for all maxSigners participants.
// The threshold is the minimum number of participants required to sign.
// The address is the G... account address the group signs for.
func NewFROSTCoordinator(verificationKey []byte, publicKeyShares [][]byte, threshold, maxSigners int, address string) (*FROSTCoordinator, error) {
	if len(verificationKey) != ed25519.PublicKeySize {
		return nil, fmt.Errorf("frost: verification key must be %d bytes, got %d", ed25519.PublicKeySize, len(verificationKey))
	}
	if threshold < 1 || threshold > maxSigners {
		return nil, fmt.Errorf("frost: threshold %d must be between 1 and %d", threshold, maxSigners)
	}
	if len(publicKeyShares) != maxSigners {
		return nil, fmt.Errorf("frost: expected %d public key shares, got %d", maxSigners, len(publicKeyShares))
	}
	if _, err := strkey.Decode(strkey.VersionByteAccountID, address); err != nil {
		return nil, fmt.Errorf("frost: invalid address %q: %w", address, err)
	}

	group := DefaultCiphersuite.Group()
	vk := group.NewElement()
	if err := vk.Decode(verificationKey); err != nil {
		return nil, fmt.Errorf("frost: decode verification key: %w", err)
	}

	pkShares := make([]*keys.PublicKeyShare, maxSigners)
	for i, pkBytes := range publicKeyShares {
		if len(pkBytes) != ed25519.PublicKeySize {
			return nil, fmt.Errorf("frost: public key share %d must be %d bytes, got %d", i, ed25519.PublicKeySize, len(pkBytes))
		}
		pk := group.NewElement()
		if err := pk.Decode(pkBytes); err != nil {
			return nil, fmt.Errorf("frost: decode public key share %d: %w", i, err)
		}
		pks, err := frost.NewPublicKeyShare(DefaultCiphersuite, uint16(i+1), pkBytes)
		if err != nil {
			return nil, fmt.Errorf("frost: create public key share %d: %w", i, err)
		}
		pkShares[i] = pks
	}

	cfg := &frost.Configuration{
		Ciphersuite:           DefaultCiphersuite,
		Threshold:             uint16(threshold),
		MaxSigners:            uint16(maxSigners),
		VerificationKey:       vk,
		SignerPublicKeyShares: pkShares,
	}
	if err := cfg.Init(); err != nil {
		return nil, fmt.Errorf("frost: init configuration: %w", err)
	}

	return &FROSTCoordinator{
		cfg:       cfg,
		threshold: uint16(threshold),
		address:   address,
		sessions:  make(map[int64]*frostSigningSession),
		roundGen:  defaultRoundGen,
	}, nil
}

// defaultRoundGen generates a cryptographically random round ID.
func defaultRoundGen() (int64, error) {
	buf := make([]byte, 8)
	if _, err := rand.Read(buf); err != nil {
		return 0, err
	}
	return int64(uint64(buf[0])<<56 | uint64(buf[1])<<48 | uint64(buf[2])<<40 | uint64(buf[3])<<32 | uint64(buf[4])<<24 | uint64(buf[5])<<16 | uint64(buf[6])<<8 | uint64(buf[7])), nil
}

// Address returns the G... account address this coordinator signs for.
func (c *FROSTCoordinator) Address() string { return c.address }

// Begin starts a new signing round for the given payload hash.
// It returns a round ID that participants use to contribute their commitments.
func (c *FROSTCoordinator) Begin(ctx context.Context, payload [32]byte) (int64, error) {
	if err := ctx.Err(); err != nil {
		return 0, fmt.Errorf("frost: begin: %w", err)
	}

	round, err := c.roundGen()
	if err != nil {
		return 0, fmt.Errorf("frost: begin: generate round: %w", err)
	}

	c.mu.Lock()
	defer c.mu.Unlock()

	c.sessions[round] = &frostSigningSession{
		round:       round,
		commitments: make(frost.CommitmentList, 0, c.threshold),
		message:     payload,
		sigShares:   make([]*frost.SignatureShare, 0, c.threshold),
	}

	return round, nil
}

// AddCommitment adds a participant's commitment to the round.
// This is called by each participant (via FROSTParticipant.Commit()).
// Returns an error if the round doesn't exist or the commitment is invalid.
func (c *FROSTCoordinator) AddCommitment(ctx context.Context, round int64, commitment *frost.Commitment) error {
	if err := ctx.Err(); err != nil {
		return fmt.Errorf("frost: add commitment: %w", err)
	}

	c.mu.Lock()
	defer c.mu.Unlock()

	session, ok := c.sessions[round]
	if !ok {
		return fmt.Errorf("frost: round %d not found", round)
	}
	if session.complete {
		return fmt.Errorf("frost: round %d already complete", round)
	}
	if err := c.cfg.ValidateCommitment(commitment); err != nil {
		return fmt.Errorf("frost: invalid commitment: %w", err)
	}

	session.commitments = append(session.commitments, commitment)
	return nil
}

// GetCommitments returns the collected commitments for a round, sorted.
// Participants need this to produce their signature shares.
func (c *FROSTCoordinator) GetCommitments(round int64) (frost.CommitmentList, error) {
	c.mu.Lock()
	defer c.mu.Unlock()

	session, ok := c.sessions[round]
	if !ok {
		return nil, fmt.Errorf("frost: round %d not found", round)
	}
	if len(session.commitments) < int(c.threshold) {
		return nil, fmt.Errorf("frost: insufficient commitments (%d/%d)", len(session.commitments), c.threshold)
	}

	// Return a sorted copy
	commitments := make(frost.CommitmentList, len(session.commitments))
	copy(commitments, session.commitments)
	commitments.Sort()
	return commitments, nil
}

// AddSignatureShare adds a participant's signature share to the round.
// If the threshold is met, it aggregates the shares into the final signature.
func (c *FROSTCoordinator) AddSignatureShare(ctx context.Context, round int64, share *frost.SignatureShare) ([]byte, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("frost: add signature share: %w", err)
	}

	c.mu.Lock()
	defer c.mu.Unlock()

	session, ok := c.sessions[round]
	if !ok {
		return nil, fmt.Errorf("frost: round %d not found", round)
	}
	if session.complete {
		return session.signature, nil
	}

	// Verify the signature share
	commitments := make(frost.CommitmentList, len(session.commitments))
	copy(commitments, session.commitments)
	commitments.Sort()

	if err := c.cfg.VerifySignatureShare(share, session.message[:], commitments); err != nil {
		return nil, fmt.Errorf("frost: invalid signature share: %w", err)
	}

	session.sigShares = append(session.sigShares, share)

	if len(session.sigShares) >= int(c.threshold) {
		// Aggregate the signature shares
		sig, err := c.cfg.AggregateSignatures(session.message[:], session.sigShares[:c.threshold], commitments, true)
		if err != nil {
			return nil, fmt.Errorf("frost: aggregate signatures: %w", err)
		}

		// Convert FROST signature to standard Ed25519 format (R || s, 64 bytes)
		rBytes := sig.R.Encode()
		sBytes := sig.Z.Encode()
		if len(rBytes) != 32 || len(sBytes) != 32 {
			return nil, fmt.Errorf("frost: unexpected signature component size: R=%d, s=%d", len(rBytes), len(sBytes))
		}
		session.signature = append(rBytes, sBytes...)
		session.complete = true
	}

	if session.complete {
		return session.signature, nil
	}
	return nil, nil
}

// GetSignature returns the aggregated signature for a completed round.
func (c *FROSTCoordinator) GetSignature(round int64) ([]byte, error) {
	c.mu.Lock()
	defer c.mu.Unlock()

	session, ok := c.sessions[round]
	if !ok {
		return nil, fmt.Errorf("frost: round %d not found", round)
	}
	if !session.complete {
		return nil, fmt.Errorf("frost: round %d not complete", round)
	}
	return session.signature, nil
}

// IsComplete reports whether the round has collected enough signature shares.
func (c *FROSTCoordinator) IsComplete(round int64) bool {
	c.mu.Lock()
	defer c.mu.Unlock()

	session, ok := c.sessions[round]
	if !ok {
		return false
	}
	return session.complete
}

// Cleanup removes a round's session data.
func (c *FROSTCoordinator) Cleanup(round int64) {
	c.mu.Lock()
	defer c.mu.Unlock()
	delete(c.sessions, round)
}

// FROSTParticipant represents a single participant in a FROST signing group.
// It holds a secret key share and can produce commitments and signature shares.
type FROSTParticipant struct {
	signer    *frost.Signer
	id        uint16
	coord     *FROSTCoordinator
	publicKey []byte // 32-byte raw public key share
}

// NewFROSTParticipant creates a participant from a secret key share.
// The secretShare is the raw 32-byte secret key share.
// The participantID is 1-indexed (1 to maxSigners).
// The publicKeyShare is the corresponding 32-byte public key share.
// The coordinator is used to submit commitments and signature shares.
func NewFROSTParticipant(secretShare, publicKeyShare []byte, participantID uint16, coord *FROSTCoordinator) (*FROSTParticipant, error) {
	if participantID < 1 || participantID > coord.cfg.MaxSigners {
		return nil, fmt.Errorf("frost: participant ID %d out of range [1, %d]", participantID, coord.cfg.MaxSigners)
	}
	if len(secretShare) != ed25519.PublicKeySize {
		return nil, fmt.Errorf("frost: secret share must be %d bytes, got %d", ed25519.PublicKeySize, len(secretShare))
	}
	if len(publicKeyShare) != ed25519.PublicKeySize {
		return nil, fmt.Errorf("frost: public key share must be %d bytes, got %d", ed25519.PublicKeySize, len(publicKeyShare))
	}

	keyShare, err := frost.NewKeyShare(DefaultCiphersuite, participantID, secretShare, publicKeyShare, coord.cfg.VerificationKey.Encode())
	if err != nil {
		return nil, fmt.Errorf("frost: create key share: %w", err)
	}

	signer, err := coord.cfg.Signer(keyShare)
	if err != nil {
		return nil, fmt.Errorf("frost: create signer: %w", err)
	}

	return &FROSTParticipant{
		signer:    signer,
		id:        participantID,
		coord:     coord,
		publicKey: publicKeyShare,
	}, nil
}

// ID returns the participant's ID (1-indexed).
func (p *FROSTParticipant) ID() uint16 { return p.id }

// PublicKey returns the participant's raw public key share (32 bytes).
func (p *FROSTParticipant) PublicKey() []byte { return p.publicKey }

// Commit generates a commitment for the current round.
// The commitment must be sent to the coordinator.
func (p *FROSTParticipant) Commit(ctx context.Context, round int64) (*frost.Commitment, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("frost: commit: %w", err)
	}
	commitment := p.signer.Commit()
	if err := p.coord.AddCommitment(ctx, round, commitment); err != nil {
		return nil, err
	}
	return commitment, nil
}

// Sign produces a signature share for the given round.
// The coordinator must have collected enough commitments first.
func (p *FROSTParticipant) Sign(ctx context.Context, round int64) (*frost.SignatureShare, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("frost: sign: %w", err)
	}

	commitments, err := p.coord.GetCommitments(round)
	if err != nil {
		return nil, err
	}

	// Get the message from the coordinator's session
	p.coord.mu.Lock()
	session := p.coord.sessions[round]
	p.coord.mu.Unlock()
	if session == nil {
		return nil, fmt.Errorf("frost: round %d not found", round)
	}

	share, err := p.signer.Sign(session.message[:], commitments)
	if err != nil {
		return nil, fmt.Errorf("frost: sign: %w", err)
	}

	// Submit the signature share to the coordinator
	_, err = p.coord.AddSignatureShare(ctx, round, share)
	return share, err
}

// TrustedDealerKeygen generates key shares for a FROST group using a
// centralized trusted dealer. This is for testing only; production should
// use distributed key generation (DKG).
//
// Returns: secretShares ([][]byte), verificationKey ([]byte), publicKeyShares ([][]byte)
// All shares are 32 bytes each. The verification key is the group public key.
func TrustedDealerKeygen(threshold, maxSigners int) ([][]byte, []byte, [][]byte, error) {
	if threshold < 1 || threshold > maxSigners {
		return nil, nil, nil, fmt.Errorf("frost: threshold %d must be between 1 and %d", threshold, maxSigners)
	}

	secretKeyShares, verificationKey, _ := debug.TrustedDealerKeygen(DefaultCiphersuite, nil, uint16(threshold), uint16(maxSigners))

	secretShares := make([][]byte, len(secretKeyShares))
	publicKeyShares := make([][]byte, len(secretKeyShares))
	for i, sk := range secretKeyShares {
		secretShares[i] = sk.SecretKey().Encode()
		publicKeyShares[i] = sk.PublicKeyShare().PublicKey().Encode()
	}

	vkBytes := verificationKey.Encode()
	return secretShares, vkBytes, publicKeyShares, nil
}

// VerifySignature verifies a FROST signature against the group verification key
// using the standard Ed25519 verifier. This confirms the signature is a valid
// Ed25519 signature for the group public key.
func VerifySignature(verificationKey, message, signature []byte) error {
	if len(verificationKey) != ed25519.PublicKeySize {
		return fmt.Errorf("verification key must be %d bytes", ed25519.PublicKeySize)
	}
	if len(signature) != ed25519.SignatureSize {
		return fmt.Errorf("signature must be %d bytes", ed25519.SignatureSize)
	}
	if !ed25519.Verify(ed25519.PublicKey(verificationKey), message, signature) {
		return errors.New("signature verification failed")
	}
	return nil
}

// FROSTSigner implements soroauth.Signer for a FROST threshold group.
// It wraps a coordinator and handles the signing flow.
//
// Note: This is a simplified implementation where the coordinator acts as
// a single party that collects shares from all participants. In a real
// deployment, participants would be separate processes/services.
type FROSTSigner struct {
	coord        *FROSTCoordinator
	participants []*FROSTParticipant
}

// NewFROSTSigner creates a Signer that coordinates FROST threshold signing
// using the provided participants. The participants must include at least
// threshold participants, and their IDs must be unique and in [1, maxSigners].
func NewFROSTSigner(coord *FROSTCoordinator, participants []*FROSTParticipant) (*FROSTSigner, error) {
	if len(participants) < int(coord.threshold) {
		return nil, fmt.Errorf("frost: need at least %d participants, got %d", coord.threshold, len(participants))
	}
	seen := make(map[uint16]bool)
	for _, p := range participants {
		if seen[p.id] {
			return nil, fmt.Errorf("frost: duplicate participant ID %d", p.id)
		}
		seen[p.id] = true
	}
	return &FROSTSigner{coord: coord, participants: participants}, nil
}

// Address returns the G... account address this signer signs for.
func (s *FROSTSigner) Address() string { return s.coord.Address() }

// Sign implements soroauth.Signer for a FROST threshold group.
// It coordinates the two-round FROST signing protocol across all participants.
func (s *FROSTSigner) Sign(ctx context.Context, preimage xdr.HashIdPreimage, payload [32]byte) (xdr.ScVal, error) {
	if err := ctx.Err(); err != nil {
		return xdr.ScVal{}, fmt.Errorf("frost: sign: %w", err)
	}

	// Verify payload matches preimage
	expected, err := soroauth.Payload(preimage)
	if err != nil {
		return xdr.ScVal{}, fmt.Errorf("frost: sign: %w", err)
	}
	if !equal32(payload, expected) {
		return xdr.ScVal{}, fmt.Errorf("frost: sign: payload mismatch: %w", soroauth.ErrSignatureMismatch)
	}

	// Start a new round
	round, err := s.coord.Begin(ctx, payload)
	if err != nil {
		return xdr.ScVal{}, fmt.Errorf("frost: sign: %w", err)
	}
	defer s.coord.Cleanup(round)

	// Round 1: Each participant commits
	for _, p := range s.participants {
		if err := ctx.Err(); err != nil {
			return xdr.ScVal{}, fmt.Errorf("frost: sign: %w", err)
		}
		if _, err := p.Commit(ctx, round); err != nil {
			return xdr.ScVal{}, fmt.Errorf("frost: participant %d commit: %w", p.id, err)
		}
	}

	// Round 2: Each participant signs
	for _, p := range s.participants {
		if err := ctx.Err(); err != nil {
			return xdr.ScVal{}, fmt.Errorf("frost: sign: %w", err)
		}
		if _, err := p.Sign(ctx, round); err != nil {
			return xdr.ScVal{}, fmt.Errorf("frost: participant %d sign: %w", p.id, err)
		}
	}

	// Get the aggregated signature
	sig, err := s.coord.GetSignature(round)
	if err != nil {
		return xdr.ScVal{}, fmt.Errorf("frost: get signature: %w", err)
	}

	// Verify the signature before returning
	if err := VerifySignature(s.coord.cfg.VerificationKey.Encode(), payload[:], sig); err != nil {
		return xdr.ScVal{}, fmt.Errorf("frost: sign: signature verification failed: %w", err)
	}

	// Build the classic account signature ScVal
	rawKey, err := rawEd25519Key(s.coord.address)
	if err != nil {
		return xdr.ScVal{}, fmt.Errorf("frost: sign: %w", err)
	}
	return soroauth.Ed25519SignatureScVal(rawKey, sig)
}

func equal32(a, b [32]byte) bool {
	for i := 0; i < 32; i++ {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func rawEd25519Key(address string) ([]byte, error) {
	raw, err := strkey.Decode(strkey.VersionByteAccountID, address)
	if err != nil {
		return nil, fmt.Errorf("%q is not an account (G…) address: %w", address, err)
	}
	return raw, nil
}

// Compile-time check
var _ soroauth.Signer = (*FROSTSigner)(nil)
